-- Membuat enum, tabel, indeks, dan trigger; periksa kolom lewat information_schema.columns dan trigger lewat information_schema.triggers.
create schema if not exists private;

do $$
begin
  create type public.profile_role as enum ('admin', 'petugas_arsip', 'staf');
exception
  when duplicate_object then null;
end;
$$;

do $$
begin
  create type public.arsip_status as enum (
    'terverifikasi',
    'menunggu_verifikasi',
    'inaktif'
  );
exception
  when duplicate_object then null;
end;
$$;

do $$
begin
  create type public.arsip_tingkat_akses as enum (
    'publik',
    'internal',
    'terbatas',
    'rahasia'
  );
exception
  when duplicate_object then null;
end;
$$;

do $$
begin
  create type public.log_audit_aksi as enum (
    'unggah',
    'ubah',
    'hapus',
    'buka',
    'unduh'
  );
exception
  when duplicate_object then null;
end;
$$;

do $$
declare
  target_table text;
  required_columns text[];
  missing_columns text[];
begin
  foreach target_table in array array['profiles', 'klasifikasi', 'arsip', 'log_audit']
  loop
    required_columns := case target_table
      when 'profiles' then array['id', 'nama_lengkap', 'role', 'unit', 'created_at']
      when 'klasifikasi' then array['id', 'kode', 'nama']
      when 'arsip' then array[
        'id', 'nomor_arsip', 'judul', 'kategori', 'klasifikasi_id',
        'unit_pencipta', 'status', 'masa_retensi_tahun', 'tanggal_retensi',
        'tingkat_akses', 'file_path', 'ukuran_file', 'diunggah_oleh',
        'created_at', 'updated_at'
      ]
      else array['id', 'user_id', 'aksi', 'arsip_id', 'detail', 'waktu']
    end;

    if pg_catalog.to_regclass(pg_catalog.format('public.%I', target_table)) is not null then
      select pg_catalog.array_agg(required.column_name order by required.column_name)
        into missing_columns
      from pg_catalog.unnest(required_columns) as required(column_name)
      left join information_schema.columns as existing
        on existing.table_schema = 'public'
        and existing.table_name = target_table
        and existing.column_name = required.column_name
      where existing.column_name is null;

      if missing_columns is not null then
        raise exception
          'public.% sudah ada tetapi tidak memiliki kolom yang diperlukan: %. Jangan lanjutkan sebelum skema lama ditinjau.',
          target_table,
          pg_catalog.array_to_string(missing_columns, ', ');
      end if;
    end if;
  end loop;
end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nama_lengkap text,
  role public.profile_role not null default 'staf',
  unit text,
  created_at timestamptz not null default now()
);

create table if not exists public.klasifikasi (
  id uuid primary key default gen_random_uuid(),
  kode text not null unique,
  nama text not null
);

create table if not exists public.arsip (
  id uuid primary key default gen_random_uuid(),
  nomor_arsip text not null unique,
  judul text not null,
  kategori text not null,
  klasifikasi_id uuid not null references public.klasifikasi (id) on delete restrict,
  unit_pencipta text not null,
  status public.arsip_status not null default 'menunggu_verifikasi',
  masa_retensi_tahun integer not null default 0
    check (masa_retensi_tahun >= 0),
  tanggal_retensi date,
  tingkat_akses public.arsip_tingkat_akses not null default 'internal',
  file_path text,
  ukuran_file bigint check (ukuran_file is null or ukuran_file >= 0),
  diunggah_oleh uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint arsip_nomor_not_blank check (length(trim(nomor_arsip)) > 0),
  constraint arsip_judul_not_blank check (length(trim(judul)) > 0)
);

create table if not exists public.log_audit (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  aksi public.log_audit_aksi not null,
  arsip_id uuid references public.arsip (id) on delete set null,
  detail jsonb not null default '{}'::jsonb,
  waktu timestamptz not null default now()
);

-- UNIQUE pada nomor_arsip sudah menyediakan indeks pencarian untuk kolom tersebut.
create index if not exists arsip_status_idx on public.arsip (status);
create index if not exists arsip_kategori_idx on public.arsip (kategori);
create index if not exists arsip_created_at_idx on public.arsip (created_at desc);
create index if not exists arsip_klasifikasi_id_idx on public.arsip (klasifikasi_id);
create index if not exists arsip_tanggal_retensi_idx on public.arsip (tanggal_retensi);
create index if not exists log_audit_waktu_idx on public.log_audit (waktu desc);
create index if not exists log_audit_user_id_idx on public.log_audit (user_id);

create or replace function public.create_profile_for_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, nama_lengkap, role)
  values (
    new.id,
    nullif(pg_catalog.btrim(coalesce(new.raw_user_meta_data ->> 'nama_lengkap', '')), ''),
    'staf'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function public.create_profile_for_new_auth_user() from public, anon, authenticated;

drop trigger if exists create_profile_after_auth_signup on auth.users;
create trigger create_profile_after_auth_signup
  after insert on auth.users
  for each row execute function public.create_profile_for_new_auth_user();

create or replace function public.set_arsip_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$$;

revoke all on function public.set_arsip_updated_at() from public, anon, authenticated;

drop trigger if exists set_arsip_updated_at on public.arsip;
create trigger set_arsip_updated_at
  before update on public.arsip
  for each row execute function public.set_arsip_updated_at();

create or replace function public.audit_arsip_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid := (select auth.uid());
  affected public.arsip%rowtype;
  action_name public.log_audit_aksi;
  linked_arsip_id uuid;
begin
  if tg_op = 'DELETE' then
    affected := old;
    action_name := 'hapus';
    linked_arsip_id := null;
  elsif tg_op = 'INSERT' then
    affected := new;
    action_name := 'unggah';
    linked_arsip_id := new.id;
  else
    affected := new;
    action_name := 'ubah';
    linked_arsip_id := new.id;
  end if;

  if actor_id is not null then
    insert into public.log_audit (user_id, aksi, arsip_id, detail)
    values (
      actor_id,
      action_name,
      linked_arsip_id,
      pg_catalog.jsonb_build_object(
        'arsip_id', affected.id,
        'nomor_arsip', affected.nomor_arsip,
        'judul', affected.judul
      )
    );
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function public.audit_arsip_write() from public, anon, authenticated;

drop trigger if exists audit_arsip_insert on public.arsip;
create trigger audit_arsip_insert
  after insert on public.arsip
  for each row execute function public.audit_arsip_write();

drop trigger if exists audit_arsip_update on public.arsip;
create trigger audit_arsip_update
  after update on public.arsip
  for each row execute function public.audit_arsip_write();

drop trigger if exists audit_arsip_delete on public.arsip;
create trigger audit_arsip_delete
  after delete on public.arsip
  for each row execute function public.audit_arsip_write();

-- Batasi default privilege agar tabel tetap tertutup sampai migrasi RLS memberi grant yang tepat.
revoke all on table public.profiles, public.klasifikasi, public.arsip, public.log_audit
  from public, anon, authenticated;
